// 调休上班的周末
const MAKEUP_WORKDAYS = new Set([
  '2026-01-04', '2026-02-14', '2026-02-28', '2026-05-09', '2026-09-20', '2026-10-10',
  '2027-01-31', '2027-02-14', '2027-05-08', '2027-09-26', '2027-10-09',
]);

export function holidayOn(date: string): string | null {
  return HOLIDAYS[date] ?? null;
}

export function makeupWorkdayOn(date: string): string | null {
  return MAKEUP_WORKDAYS.has(date) ? '调休上班' : null;
}

const DAY_MS = 86400000;

function eachDate(start: string, days: number): string[] {
  const base = Date.parse(`${start}T00:00:00Z`);
  if (!Number.isFinite(base) || days <= 0) return [];
  return Array.from({ length: Math.min(days, 60) }, (_, i) => new Date(base + i * DAY_MS).toISOString().slice(0, 10));
}

/** 计划期内的法定节假日（含假期中的每一天）。 */
export function holidaysInRange(start: string, days: number): HolidayEntry[] {
  return eachDate(start, days)
    .filter((d) => HOLIDAYS[d])
    .map((d) => ({ date: d, name: HOLIDAYS[d] }));
}

/** 计划期内的调休上班日。 */
export function makeupWorkdaysInRange(start: string, days: number): string[] {
  return eachDate(start, days).filter((d) => MAKEUP_WORKDAYS.has(d));
}